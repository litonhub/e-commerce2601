// Local dummy product data. The shape mirrors exactly what the real
// backend used to return for a single product (see the field-by-field
// usage in src/pages/Shop.jsx, src/pages/ProductDetails.jsx, and the
// homepage sections), so every page/component that already consumes
// products keeps working unchanged once a real backend is reconnected.
//
// Field notes:
// - title / description are { en, bn } so the site's existing bn/en
//   toggle (see src/locales) works on product content too.
// - tags is a plain English array — it lines up directly with the
//   fixed tag filter list in Shop.jsx (Healthy, Low fat, Vegetarian, …).
// - price is the CURRENT (already-discounted) price; the original
//   price is derived elsewhere as price / (1 - discountPercentage/100),
//   exactly like the existing UI already does.
// - category values are lowercase on purpose — Shop.jsx compares them
//   case-sensitively-lowered against its own hardcoded filter list.
// - bestSeller / hotDeals / popular are simple flags the homepage
//   sections (BestSeller.jsx, HotDeals.jsx, PopularProducts.jsx)
//   already filter on via query params of the same name.
//
// A handful of products intentionally reuse a category "fallback" icon
// (e.g. snacks.png) instead of a dedicated product photo, since this
// repo only ships a subset of real product photos locally. Swap in a
// real photo any time by changing that one import.

